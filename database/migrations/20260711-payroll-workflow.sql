CREATE TABLE IF NOT EXISTS payroll_workflow_batches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CompanyID INT NOT NULL,
    PMonth TINYINT NOT NULL,
    PYear SMALLINT NOT NULL,
    PType VARCHAR(10) NOT NULL,
    Status VARCHAR(40) NOT NULL,
    TotalStaff INT NOT NULL DEFAULT 0,
    TotalBasic DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalAllowances DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalGross DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalTaxable DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalTax DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalNassitEmployee DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalNassitEmployer DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalDeductions DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    TotalNet DECIMAL(18,2) NOT NULL DEFAULT 0.00,
    PayrollRowCount INT NOT NULL DEFAULT 0,
    PayrollChecksum VARCHAR(128) NULL,
    ProcessedBy BIGINT UNSIGNED NULL,
    ProcessedAt DATETIME NULL,
    SubmittedToManagerBy BIGINT UNSIGNED NULL,
    SubmittedToManagerAt DATETIME NULL,
    ManagerEndorsedBy BIGINT UNSIGNED NULL,
    ManagerEndorsedAt DATETIME NULL,
    ManagerComments TEXT NULL,
    AuditorEndorsedBy BIGINT UNSIGNED NULL,
    AuditorEndorsedAt DATETIME NULL,
    AuditorComments TEXT NULL,
    FinalApprovedBy BIGINT UNSIGNED NULL,
    FinalApprovedAt DATETIME NULL,
    EntityHeadComments TEXT NULL,
    PostedToAccountsBy BIGINT UNSIGNED NULL,
    PostedToAccountsAt DATETIME NULL,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_payroll_workflow_batch (CompanyID, PMonth, PYear, PType),
    KEY idx_payroll_workflow_status (Status),
    KEY idx_payroll_workflow_period (CompanyID, PYear, PMonth, PType)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payroll_workflow_actions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    WorkflowBatchID BIGINT UNSIGNED NOT NULL,
    CompanyID INT NOT NULL,
    PMonth TINYINT NOT NULL,
    PYear SMALLINT NOT NULL,
    PType VARCHAR(10) NOT NULL,
    Action VARCHAR(50) NOT NULL,
    FromStatus VARCHAR(40) NULL,
    ToStatus VARCHAR(40) NOT NULL,
    ActionBy BIGINT UNSIGNED NOT NULL,
    ActionAt DATETIME NOT NULL,
    Comments TEXT NULL,
    Result VARCHAR(20) NOT NULL,
    Metadata LONGTEXT NULL,
    KEY idx_payroll_workflow_actions_batch (WorkflowBatchID),
    KEY idx_payroll_workflow_actions_period (CompanyID, PYear, PMonth, PType),
    KEY idx_payroll_workflow_actions_action (Action, ActionAt)
) ENGINE=InnoDB;

ALTER TABLE payroll_workflow_batches ENGINE=InnoDB;
ALTER TABLE payroll_workflow_actions ENGINE=InnoDB;
