CREATE TABLE IF NOT EXISTS workflow_notifications (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CompanyID INT NOT NULL,
    RecipientUserID INT NOT NULL,
    RecipientRole VARCHAR(50) NULL,
    NotificationType VARCHAR(80) NOT NULL,
    Module VARCHAR(80) NOT NULL,
    Title VARCHAR(255) NOT NULL,
    Message TEXT NOT NULL,
    ReferenceType VARCHAR(80) NULL,
    ReferenceID VARCHAR(255) NULL,
    ActionURL VARCHAR(500) NULL,
    EventKey VARCHAR(255) NOT NULL,
    IsRead TINYINT NOT NULL DEFAULT 0,
    ReadAt DATETIME NULL,
    CreatedBy INT NULL,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ExpiresAt DATETIME NULL,
    Metadata LONGTEXT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_workflow_notifications_eventkey (EventKey),
    KEY idx_workflow_notifications_recipient_read (RecipientUserID, IsRead),
    KEY idx_workflow_notifications_company_role (CompanyID, RecipientRole),
    KEY idx_workflow_notifications_created_at (CreatedAt),
    KEY idx_workflow_notifications_module_reference (Module, ReferenceID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
