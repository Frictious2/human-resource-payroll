router.post('/payroll/approvals/:batchId/return', entityHeadController.postPayrollReturn);
router.post('/payroll/approvals/:batchId/reject', entityHeadController.postPayrollReject);
router.get('/payroll/reversals', payrollReversalController.getEntityHeadQueue);
router.get('/payroll/reversals/:requestId', payrollReversalController.getEntityHeadDetail);
router.post('/payroll/reversals/:requestId/approve', payrollReversalController.postEntityHeadApprove);
