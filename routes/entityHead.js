router.post('/payroll/reopen/:requestId/approve', payrollReopenController.postEntityHeadApprove);
router.post('/payroll/reopen/:requestId/return', payrollReopenController.postEntityHeadReturn);
router.post('/payroll/reopen/:requestId/reject', payrollReopenController.postEntityHeadReject);
router.get('/yearly-payments', yearlyPaymentController.getEntityHeadQueue);
router.get('/yearly-payments/:batchId', yearlyPaymentController.getEntityHeadDetail);
router.post('/yearly-payments/:batchId/approve', yearlyPaymentController.postEntityHeadApprove);
router.post('/yearly-payments/:batchId/return', yearlyPaymentController.postEntityHeadReturn);
router.post('/yearly-payments/:batchId/reject', yearlyPaymentController.postEntityHeadReject);
router.get('/staff', entityHeadController.getStaffOverview);
router.get('/attendance', entityHeadController.getAttendanceSummary);
router.get('/leave', entityHeadController.getLeaveSummary);
router.get('/transfers', entityHeadController.getTransferPromotionSummary);
router.get('/training', entityHeadController.getTrainingSummary);
router.get('/reports', entityHeadController.getReports);

module.exports = router;
